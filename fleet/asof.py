"""
Срез состояния на дату (ТЗ §7) — чистая логика без обращения к БД.

Для завершённого месяца состояние ТО считается на конец месяца по показаниям и
ТО, относящимся к той дате, а не по сегодняшнему пробегу (ТЗ §7: «Не пересчитывать
историческую карточку по сегодняшнему пробегу»). Здесь — выбор базы: какое
принятое показание и какое подтверждённое ТО актуальны на дату среза. Расчёт
остатка и цвета — в `maintenance.maintenance_state`.

Возвращается ВЫБРАННАЯ запись целиком (не только число): дашборд берёт из неё и
значение для расчёта, и дату с источником для показа строки — один источник
истины для счётчиков и для таблицы.

Решение (фальсифицируемое): база ТО на дату среза — ТО с наибольшей датой
выполнения `performed_on <= cut`. Ключ — дата выполнения, не дата подтверждения:
подтверждение сотрудника может прийти позже, но удостоверяет работу, физически
выполненную до среза. Сломать: ТО, выполненное после среза, базой стать не должно
(тест `test_asof_ignores_maintenance_after_cut`).
"""
from __future__ import annotations

from datetime import date
from typing import TypeVar

T = TypeVar("T", bound=tuple)


def accepted_reading_asof(
    readings: list[tuple[int, date, str]], cut: date
) -> tuple[int, date, str] | None:
    """
    Актуальное принятое показание на дату среза.

    readings — список (значение_км, дата_измерения, источник) ПРИНЯТЫХ показаний
        любого источника, не обязательно отсортированный. Показания на проверке
        сюда не попадают (их отсеивает вызывающая сторона).
    cut — дата среза включительно.

    Берётся показание с наибольшей датой измерения не позже среза; при равных
    датах — наибольшее значение (одометр растёт). None, если принятых показаний на
    эту дату нет.
    """
    eligible = [r for r in readings if r[1] <= cut]
    if not eligible:
        return None
    return max(eligible, key=lambda r: (r[1], r[0]))


def confirmed_maint_asof(
    maintenances: list[tuple[int, date]], cut: date
) -> tuple[int, date] | None:
    """
    База ТО на дату среза: последнее ПОДТВЕРЖДЁННОЕ ТО с датой выполнения не позже
    среза.

    maintenances — список (пробег_км, дата_выполнения) только ПОДТВЕРЖДЁННЫХ ТО
        (status=confirmed), не обязательно отсортированный.
    cut — дата среза включительно.

    Берётся запись с наибольшей датой выполнения не позже среза; при равных датах —
    наибольший пробег. None, если подтверждённой базы на эту дату нет (серый статус
    «нет данных», в просрочку не относить — ТЗ §6).
    """
    eligible = [m for m in maintenances if m[1] <= cut]
    if not eligible:
        return None
    return max(eligible, key=lambda m: (m[1], m[0]))
